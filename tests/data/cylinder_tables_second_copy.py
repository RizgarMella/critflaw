def _extended_table_two_halves(name, ab_axis, bri_axis, rows):
    """Build [a/B][B/r_i] blocks Mm, Mb from rows printed with two B/r_i halves side by side."""
    mm = [[NAN] * len(bri_axis) for _ in ab_axis]
    mb = [[NAN] * len(bri_axis) for _ in ab_axis]
    count = 0
    seen = set()
    for row in rows:
        ab = row[0]
        if len(row) != 1 + 2 * len(bri_axis):
            raise ValueError(f"{name}: row a/B={ab} has {len(row)} entries")
        if ab in seen:
            raise ValueError(f"{name}: duplicate row a/B={ab}")
        seen.add(ab)
        i = ab_axis.index(ab)
        for k in range(len(bri_axis)):
            mm[i][k] = float(row[1 + 2 * k])
            mb[i][k] = float(row[2 + 2 * k])
            count += 2
    if len(seen) != len(ab_axis):
        raise ValueError(f"{name}: {len(seen)} rows typed, {len(ab_axis)} expected")
    table = {"axes": [("a/B", ab_axis), ("B/r_i", bri_axis)], "values": {"Mm": mm, "Mb": mb}}
    return table, count


