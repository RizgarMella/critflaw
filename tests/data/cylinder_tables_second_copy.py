def _grid_tables(prefix, lambda_rows, columns):
    """Build the four (lambda x r_m/B) grids M_1..M_4 from per-column records."""
    grids = {k: [[NAN] * len(_RMB_COLS) for _ in lambda_rows] for k in range(4)}
    counts = {k: 0 for k in range(4)}
    for j, rmb in enumerate(_RMB_COLS):
        for lam, m1, m2, m3, m4 in columns[rmb]:
            if lam not in lambda_rows:
                raise ValueError(f"{prefix}: lambda {lam} not in row list")
            i = lambda_rows.index(lam)
            for k, v in enumerate((m1, m2, m3, m4)):
                if grids[k][i][j] == grids[k][i][j]:  # already numeric: duplicate record
                    raise ValueError(f"{prefix}: duplicate cell lambda={lam}, r_m/B={rmb}")
                grids[k][i][j] = float(v)
                counts[k] += 1
    tables = {}
    cell_counts = {}
    for k, suffix in enumerate("abcd"):
        key = f"{prefix}{suffix}"
        tables[key] = {
            "axes": [("lambda", tuple(lambda_rows)), ("r_m/B", _RMB_COLS)],
            "values": grids[k],
        }
        cell_counts[key] = counts[k]
    return tables, cell_counts


