_SURFACE_BLOCKS = ("Mm_d", "Mb_d", "Mm_s", "Mb_s")


def _surface_table(name, ac_axis, ab_axis, bri_axis, rows):
    """Build the four [a/c][a/B][B/r_i] blocks from the printed rows (two B/r_i halves per row)."""
    if len(bri_axis) != 2:
        raise ValueError(f"{name}: expected two B/r_i halves")
    blocks = {
        b: [[[NAN] * len(bri_axis) for _ in ab_axis] for _ in ac_axis] for b in _SURFACE_BLOCKS
    }
    count = 0
    seen = set()
    for row in rows:
        ac, ab = row[0], row[1]
        if len(row) != 2 + 4 * len(bri_axis):
            raise ValueError(f"{name}: row a/c={ac}, a/B={ab} has {len(row)} entries")
        if (ac, ab) in seen:
            raise ValueError(f"{name}: duplicate row a/c={ac}, a/B={ab}")
        seen.add((ac, ab))
        i = ac_axis.index(ac)
        j = ab_axis.index(ab)
        for k in range(len(bri_axis)):
            half = row[2 + 4 * k : 6 + 4 * k]
            for b, v in zip(_SURFACE_BLOCKS, half, strict=True):
                blocks[b][i][j][k] = float(v)
                count += 1
    expected = len(ac_axis) * len(ab_axis)
    if len(seen) != expected:
        raise ValueError(f"{name}: {len(seen)} rows typed, {expected} expected")
    table = {
        "axes": [("a/c", ac_axis), ("a/B", ab_axis), ("B/r_i", bri_axis)],
        "values": blocks,
    }
    return table, count


